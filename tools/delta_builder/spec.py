def _base(**over) -> dict:
    cfg = {
        "deployment": {"name": "delta", "project_dir": "delta"},
        "server": "wsgi",
        # delta's beat recomputes the recommendation similarity matrix nightly
        # and its vault work is queued, so the worker is part of the host rather
        # than an option — no capability turns it on or off.
        "services": {"celery": True},
        "target": {"type": "local"},
        "admin": {"username": "admin", "person": {"display_name": "Delta Admin"}},
        "env": {
            "DJANGO_ENV": "PROD",
            "DEBUG": "0",
            "RESET": "0",
            "FULL_INGRESS": "1",
            "LANGUAGE_CODE": "pl",
            "DB_NAME": "delta",
            "DB_USER": "delta",
            "DB_PASSWORD": "change_me_in_prod",
            "DB_PORT": "5432",
            "REDIS_CACHE_URL": "redis://redis:6379/1",
            "CELERY_BROKER_URL": "redis://redis:6379/0",
            "PLATFORM_NAME": "Delta",
            "PLATFORM_LOGO_PATH": "../data/img/delta.png",
            "EMAIL_BACKEND": "console",
        },
        "nginx": {"http_port": 8082, "https_port": 8443, "bind": "127.0.0.1"},
        "ssl": {"mode": "gervazy"},
        # No `cert` here on purpose: each preset supplies the whole block. An
        # empty list does not survive the YAML round-trip (it parses back as
        # None), so a half-filled cert cannot be a shared default.
    }
    for key, value in over.items():
        if isinstance(value, dict) and isinstance(cfg.get(key), dict):
            cfg[key] = {**cfg[key], **value}
        else:
            cfg[key] = value
    return cfg


