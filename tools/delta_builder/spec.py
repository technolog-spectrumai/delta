"""What the Delta Builder offers: fields, capabilities, presets and branding.

delta is a **fixed-shape** host, and that shapes this file more than anything
else. It is a maths e-learning platform: the LMS core (courses, tasks, skills,
notes) is what delta *is*, so none of it is a toggle. What varies is the
surrounding capabilities — the authoring editors, the library, subscriptions,
video playback, social sign-in — plus the ordinary deployment surface (ports,
TLS, target, database, admin).

Two rules govern the Features tab, and both exist so a generated config cannot
describe a broken host:

* **Capabilities are whole.** "Authoring tools" installs the editor base, memo,
  cyprian and primula together, because cyprian imports memo's sanitisers and
  raises ``cyprian.E001`` without it, and both build their file views on
  ``toto.editor``. Ticking three of the four is not a configuration anyone wants
  and not one this builder can produce.
* **Anything that cannot be switched off is not offered.** The LMS core is
  welded by foreign keys (academy → quizzes/competence/palimpsest), and
  ``toto.quota`` is imported unguarded by the vendored vault, so a host without
  it does not start. Neither appears here as a tick that would lie.

Every flag is **subtractive** — default on, written as ``"0"`` only when you
untick it — so a config that names none of them builds the delta that has always
shipped, and the two profiles in ``delta/deploy/configs/`` keep meaning exactly
what they meant before the flags existed.

Deliberately NOT offered: a Package tab (delta's deploy.py fork has no payload
manifest and the repo ships no ``run.sh``/``issue_letsencrypt.sh``), a
``--dry-run`` push (the fork's argparse rejects it), and ``server: asgi``
(delta is WSGI — it has no ASGI entry point and no websocket consumers).
"""

