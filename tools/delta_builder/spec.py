def _preset_config(host_root: Path, caps: tuple[str, ...], over: dict) -> dict:
    cfg = _base(**over)
    env = cfg.setdefault("env", {})
    for cap in CAPABILITIES:
        # Subtractive flags: an untouched capability is ON, so only the ones the
        # preset leaves out are written — and written as an explicit "0", so the
        # file says what it decided rather than relying on a default.
        for flag in cap.flags:
            env[flag] = "1" if cap.key in caps else "0"
    return derive_config(CAPABILITIES, host_root, cfg)


def build_presets(host_root: Path) -> tuple[Preset, ...]:
    return tuple(
        Preset(key, label, blurb, _preset_config(host_root, caps, over))
        for key, label, blurb, caps, over in PRESET_SPECS
    )


def extra_checks(cfg: dict) -> list[Issue]:
    """delta-specific consistency the generic rules cannot know about."""
    found: list[Issue] = []

    env = cfg.get("env") or {}
    services = cfg.get("services") or {}

    # The worker is not optional on this host: beat recomputes the
    # recommendation matrix nightly, and without a broker every queued task
    # falls back to running inline in the request that asked for it.
    if not services.get("celery"):
        found.append(Issue(
            "services.celery",
            "delta runs a celery worker and beat — the recommendation matrix is "
            "recomputed nightly. Without them the schedule never fires and "
            "queued work runs inline in a web request instead.",
            WARNING))

    # RESET drops the schema on every container start. On anything but a local
    # target that is data loss, and deploy.py refuses it outright.
    if str(env.get("RESET", "")) == "1" and get_path(cfg, "target.type") not in ("local", None, ""):
        found.append(Issue(
            "env.RESET",
            "RESET=1 wipes the database on every start — never on a remote "
            "target. deploy.py refuses this combination.",
        ))

    # A trusted certificate needs a name to be issued for, and an address to be
    # reached at during the challenge.
    if get_path(cfg, "ssl.mode") == "letsencrypt":
        if not (get_path(cfg, "ssl.domain") or env.get("PLATFORM_DOMAIN")):
            found.append(Issue(
                "ssl.domain",
                "Let's Encrypt needs a domain that resolves to this host — set "
                "ssl.domain or PLATFORM_DOMAIN.",
            ))
        if not get_path(cfg, "ssl.email"):
            found.append(Issue(
                "ssl.email",
                "Let's Encrypt requires a contact address for renewal warnings.",
            ))

    # Console email accepts a password reset and then drops it on the floor.
    # Fine locally, a silent dead end on a server.
    if (env.get("EMAIL_BACKEND", "console") == "console"
            and get_path(cfg, "target.type") == "ssh"):
        found.append(Issue(
            "env.EMAIL_BACKEND",
            "the console backend prints mail to the container log instead of "
            "sending it, so 'Forgot password?' silently never arrives. Set "
            "EMAIL_BACKEND: smtp for a real deployment.",
            WARNING))

    # Demo content on a public server is a decision, not an accident.
    if (str(env.get("FULL_INGRESS", "")) == "1"
            and get_path(cfg, "target.type") == "ssh"):
        found.append(Issue(
            "env.FULL_INGRESS",
            "this seeds the demo maths course tree and sample subscription "
            "plans into a production database. Deliberate only if you want "
            "example content visible to real students.",
            WARNING))

    return found


